; NexOS - VBE 帧缓冲图形驱动 (支持 24bpp 和 32bpp)
section .data
global framebuffer_addr
global screen_width
global screen_height
global screen_pitch
global screen_bpp
framebuffer_addr dd 0
screen_width    dd 800
screen_height   dd 600
screen_pitch    dd 2400
screen_bpp      dd 24

section .text
global vga_init
vga_init:
    ; 重新编程 VGA PCI BAR0 确保帧缓冲映射 (00:02.0)
    mov dx, 0xCF8
    mov eax, 0x80000000 | (0 << 16) | (2 << 11) | (0 << 8) | 0x10
    out dx, eax
    mov dx, 0xCFC
    mov eax, 0xE0000000
    out dx, eax
    mov [framebuffer_addr], eax

    mov eax, [0x8004]
    mov [screen_pitch], eax
    mov eax, [0x8008]
    mov [screen_width], eax
    mov eax, [0x800C]
    mov [screen_height], eax
    mov eax, [0x8010]
    mov [screen_bpp], eax
    ret

; 画一个像素点
; 参数: x, y, color (0x00RRGGBB)
global put_pixel
put_pixel:
    push ebp
    mov ebp, esp
    push ebx
    mov eax, [ebp+12]
    mul dword [screen_pitch]
    mov ecx, [ebp+8]
    cmp dword [screen_bpp], 32
    je .bpp32
    ; 24bpp: x * 3
    lea ecx, [ecx + ecx*2]
    jmp .calc_done
.bpp32:
    shl ecx, 2
.calc_done:
    add eax, ecx
    add eax, [framebuffer_addr]
    mov edx, [ebp+16]
    mov [eax], dl        ; B
    mov [eax+1], dh      ; G
    shr edx, 16
    mov [eax+2], dl      ; R
    pop ebx
    pop ebp
    ret

; 填充矩形
; 参数: x, y, w, h, color
global fill_rect
fill_rect:
    push ebp
    mov ebp, esp
    push ebx
    push esi
    push edi

    ; 计算起始地址
    mov eax, [ebp+12]
    mul dword [screen_pitch]
    mov esi, [ebp+8]
    cmp dword [screen_bpp], 32
    je .bpp32
    lea esi, [esi + esi*2]
    jmp .calc
.bpp32:
    shl esi, 2
.calc:
    add eax, esi
    mov edi, [framebuffer_addr]
    add edi, eax

    mov edx, [ebp+24]   ; color
    mov ebx, [ebp+20]   ; h (行数)

.row_loop:
    mov ecx, [ebp+16]   ; w (像素数)
    push edi
.pixel_loop:
    ; 写一个像素
    mov [edi], dl
    mov [edi+1], dh
    push edx
    shr edx, 16
    mov [edi+2], dl
    pop edx
    ; 下一个像素
    cmp dword [screen_bpp], 32
    je .add4
    add edi, 3
    jmp .next
.add4:
    add edi, 4
.next:
    dec ecx
    jnz .pixel_loop
    pop edi
    add edi, [screen_pitch]
    dec ebx
    jnz .row_loop

    pop edi
    pop esi
    pop ebx
    pop ebp
    ret

; 清屏
global clear_screen
clear_screen:
    push ebp
    mov ebp, esp
    push dword [ebp+8]
    push dword [screen_height]
    push dword [screen_width]
    push 0
    push 0
    call fill_rect
    add esp, 20
    pop ebp
    ret

; 绘制 8x16 字体字符
; 参数: x, y, char, color
global draw_char_fast
draw_char_fast:
    push ebp
    mov ebp, esp
    push ebx
    push esi
    push edi

    mov eax, [ebp+16]
    mov esi, font_data
    mov ebx, eax
    shl ebx, 4
    add esi, ebx

    ; 计算起始地址
    mov eax, [ebp+12]
    mul dword [screen_pitch]
    mov edi, [ebp+8]
    cmp dword [screen_bpp], 32
    je .bpp32
    lea edi, [edi + edi*2]
    jmp .calc
.bpp32:
    shl edi, 2
.calc:
    add eax, edi
    mov edi, [framebuffer_addr]
    add edi, eax

    mov edx, [ebp+20]
    mov ecx, 16
.row:
    mov al, [esi]
    push ecx
    push edi
    mov ecx, 8
.col:
    test al, 0x80
    jz .skip
    mov [edi], dl
    mov [edi+1], dh
    push edx
    shr edx, 16
    mov [edi+2], dl
    pop edx
.skip:
    shl al, 1
    cmp dword [screen_bpp], 32
    je .add4
    add edi, 3
    jmp .next
.add4:
    add edi, 4
.next:
    dec ecx
    jnz .col
    pop edi
    add edi, [screen_pitch]
    inc esi
    pop ecx
    dec ecx
    jnz .row

    pop edi
    pop esi
    pop ebx
    pop ebp
    ret

; 绘制字符串
global draw_string
draw_string:
    push ebp
    mov ebp, esp
    push ebx
    push esi
    mov esi, [ebp+16]
    mov ebx, [ebp+8]
.loop:
    mov al, [esi]
    test al, al
    jz .done
    push dword [ebp+20]
    push eax
    push dword [ebp+12]
    push ebx
    call draw_char_fast
    add esp, 16
    add ebx, 8
    inc esi
    jmp .loop
.done:
    pop esi
    pop ebx
    pop ebp
    ret

